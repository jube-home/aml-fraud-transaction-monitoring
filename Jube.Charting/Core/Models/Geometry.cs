namespace Jube.Charting.Core.Models
{
    internal readonly record struct Rect(double Left, double Top, double Right, double Bottom)
    {
        public double Width => Right - Left;
        public double Height => Bottom - Top;
        public double CenterX => (Left + Right) / 2;
        public double CenterY => (Top + Bottom) / 2;
    }

    internal readonly record struct Tick(double Value, double Position, string Label);

    internal readonly record struct LegendEntry(string Label, int Series, LegendShape Shape = LegendShape.Square);

    internal readonly record struct TipRow(string Text, bool Bold = false, int? Series = null);
}